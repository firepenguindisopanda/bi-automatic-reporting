"""Message bodies.

Styled with the same editorial tokens as the app and the PDF: warm paper, ink
text, one rust accent, hairline rules, no gradients. Mail clients strip most
CSS, so everything is inline and the layout is a plain single column.
"""

PAPER = "#FBFAF7"
INK = "#1A1815"
INK_MUTED = "#6B655C"
RULE = "#E4DFD5"
ACCENT = "#9A3F1F"

SECTIONS = (
    "Executive summary",
    "Business profile",
    "Market analysis",
    "Competitive analysis",
    "SWOT analysis",
    "Recommendations and risk factors",
)


def report_subject(company_name: str) -> str:
    return f"Business Intelligence Report: {company_name}"


def report_html(company_name: str) -> str:
    items = "".join(
        f'<li style="margin:0 0 6px 0;color:{INK};">{section}</li>' for section in SECTIONS
    )
    return f"""\
<!doctype html>
<html>
<body style="margin:0;padding:0;background:{PAPER};">
  <div style="max-width:600px;margin:0 auto;padding:32px 24px;
              font-family:Georgia,'Times New Roman',serif;color:{INK};
              font-size:16px;line-height:1.6;">
    <p style="margin:0 0 4px 0;font-size:12px;letter-spacing:.08em;
              text-transform:uppercase;color:{INK_MUTED};
              font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;">
      Business Intelligence
    </p>
    <h1 style="margin:0 0 16px 0;font-size:26px;font-weight:normal;color:{INK};">
      Your report for {company_name} is ready
    </h1>
    <hr style="border:0;border-top:1px solid {RULE};margin:0 0 20px 0;">
    <p style="margin:0 0 12px 0;">The attached report covers:</p>
    <ul style="margin:0 0 24px 0;padding-left:20px;">{items}</ul>
    <p style="margin:0 0 24px 0;color:{INK_MUTED};font-size:14px;">
      Both PDF and Word versions are attached.
    </p>
    <hr style="border:0;border-top:1px solid {RULE};margin:0 0 16px 0;">
    <p style="margin:0;font-size:12px;color:{INK_MUTED};
              font-family:-apple-system,Segoe UI,Helvetica,Arial,sans-serif;">
      Generated by the Business Intelligence System
    </p>
  </div>
</body>
</html>"""


def report_text(company_name: str) -> str:
    """Plain-text alternative. Its absence hurts deliverability."""
    sections = "\n".join(f"  - {section}" for section in SECTIONS)
    return (
        f"Your Business Intelligence report for {company_name} is ready.\n\n"
        f"The attached report covers:\n{sections}\n\n"
        "Both PDF and Word versions are attached.\n\n"
        "-- \nGenerated by the Business Intelligence System\n"
    )


