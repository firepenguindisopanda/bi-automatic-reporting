import { NavLink, Outlet } from 'react-router-dom'
import { useTheme } from '../hooks/useTheme'

const THEME_LABEL = {
  system: 'Match system',
  light: 'Light',
  dark: 'Dark',
} as const

export default function Layout() {
  const { theme, cycle } = useTheme()

  return (
    <div className="min-h-screen bg-paper">
      <a
        href="#main"
        className="sr-only focus:not-sr-only focus:absolute focus:left-4 focus:top-4 focus:z-10
                   focus:rounded-sm focus:border focus:border-rule-strong focus:bg-surface
                   focus:px-3 focus:py-2 focus:font-sans focus:text-sm"
      >
        Skip to content
      </a>

      <header className="border-b border-rule">
        <div className="mx-auto flex max-w-3xl items-center gap-4 px-5 py-4 sm:gap-6">
          <NavLink to="/" className="shrink-0 text-[19px] tracking-tight no-underline">
            {/* The full name needs room; on a phone the initials carry it. */}
            <span className="sm:hidden">BI</span>
            <span className="hidden sm:inline">Business Intelligence</span>
          </NavLink>

          <nav className="flex shrink-0 gap-4 font-sans text-[13px] sm:gap-5">
            <Tab to="/">Analysis</Tab>
            <Tab to="/research">
              <span className="sm:hidden">Research</span>
              <span className="hidden sm:inline">Market research</span>
            </Tab>
          </nav>

          <button
            type="button"
            onClick={cycle}
            title={`Theme: ${THEME_LABEL[theme]}`}
            className="ml-auto min-h-11 rounded-sm px-2 font-sans text-[12px] text-muted
                       hover:text-accent"
          >
            {THEME_LABEL[theme]}
          </button>
        </div>
      </header>

      <main id="main" className="mx-auto max-w-3xl px-5 py-10">
        <Outlet />
      </main>

      <footer className="mx-auto max-w-3xl border-t border-rule px-5 py-6">
        <p className="font-sans text-[12px] text-faint">
          Reports are generated by language models and should be checked before use.
        </p>
      </footer>
    </div>
  )
}

function Tab({ to, children }: { to: string; children: React.ReactNode }) {
  return (
    <NavLink
      to={to}
      end={to === '/'}
      className={({ isActive }) =>
        [
          // min-h-6 keeps the target at the 24px WCAG 2.2 minimum; these are
          // standalone nav links, so the inline-text exception does not apply.
          'inline-flex min-h-6 items-center no-underline decoration-1 underline-offset-[6px]',
          isActive ? 'text-accent underline' : 'text-muted hover:text-ink',
        ].join(' ')
      }
    >
      {children}
    </NavLink>
  )
}
